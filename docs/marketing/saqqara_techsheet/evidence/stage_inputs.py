"""
Stage the inputs of the Saqqara tech-sheet measurements into one bench directory.

Author: Olivier Vitrac, PhD, HDR | olivier.vitrac@adservio.fr | Adservio

    python stage_inputs.py --repo <RAGIX checkout> --bench <bench dir>

Public inputs are copied from the checkout, and only if `git ls-files` lists them: an untracked
file is refused, so nothing private can enter by accident. Three SYNTHETIC inputs (the same small
table as a word-processing document, a spreadsheet and a presentation) are generated by the
repository's own fixture generators, `tests/saqqara/generators.py`; they are labelled as such in
the manifest and in every result derived from them.

Writes <bench>/inputs/public/*, <bench>/inputs/synthetic/* and <bench>/inputs/MANIFEST.json (id,
relative path, bytes, sha256, origin). An existing file with other bytes is refused, never
overwritten. The bench is run from <bench> with relative paths, so that a tree's recorded source
path is the same on every host.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

#: (id, path in the checkout, path under inputs/, label)
PUBLIC = [
    ("techsheet_pdf", "docs/marketing/ragix_techsheet/Adservio-RAGIXTechSheet.pdf",
     "public/Adservio-RAGIXTechSheet.pdf", "public, tracked: the RAGIX tech sheet (A4)"),
    ("slides_pdf", "docs/marketing/ragix_techsheet/ragix-tech-sheet/RAGIX-Tech-Sheet-Slides.pdf",
     "public/RAGIX-Tech-Sheet-Slides.pdf", "public, tracked: the RAGIX tech-sheet slides"),
    ("sovereign_pdf", "docs/SOVEREIGN_LLM_OPERATIONS.pdf",
     "public/SOVEREIGN_LLM_OPERATIONS.pdf", "public, tracked: Sovereign LLM operations (A4)"),
    ("saqqara_readme_md", "ragix_kernels/saqqara/README.md",
     "public/saqqara_README.md", "public, tracked: the Saqqara README"),
    ("koas_saqqara_md", "docs/KOAS_SAQQARA.md",
     "public/KOAS_SAQQARA.md", "public, tracked: the Saqqara user reference"),
]

#: (id, generator name in tests/saqqara/generators.py, path under inputs/)
SYNTHETIC = [
    ("twin_grid_docx", "twin_grid_docx", "synthetic/twin_grid.docx"),
    ("twin_grid_xlsx", "twin_grid_xlsx", "synthetic/twin_grid.xlsx"),
    ("twin_grid_pptx", "twin_grid_pptx", "synthetic/twin_grid.pptx"),
]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def place(source: Path, target: Path) -> None:
    """Copy, or accept an identical file already there; refuse a different one."""
    if target.exists():
        if sha256(target) != sha256(source):
            raise SystemExit(f"refused: {target} exists with other bytes")
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo", required=True)
    parser.add_argument("--bench", required=True)
    args = parser.parse_args()
    repo, bench = Path(args.repo).resolve(), Path(args.bench).resolve()
    inputs = bench / "inputs"

    tracked = set(subprocess.run(["git", "-C", str(repo), "ls-files"], check=True,
                                 capture_output=True, text=True).stdout.splitlines())
    head = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"], check=True,
                          capture_output=True, text=True).stdout.strip()
    entries = []
    for ident, rel, dest, label in PUBLIC:
        if rel not in tracked:
            raise SystemExit(f"refused: {rel} is not tracked in {repo}")
        place(repo / rel, inputs / dest)
        entries.append({"id": ident, "path": f"inputs/{dest}", "origin": label,
                        "repo_path": rel, "synthetic": False})

    sys.path.insert(0, str(repo / "tests" / "saqqara"))
    import generators as G  # the repository's own fixture generators

    with tempfile.TemporaryDirectory(dir=bench) as tmp:
        for ident, name, dest in SYNTHETIC:
            made = G.FIXTURES[name](G.fixture_path(name, Path(tmp)))
            place(made, inputs / dest)
            entries.append({"id": ident, "path": f"inputs/{dest}",
                            "origin": f"SYNTHETIC: tests/saqqara/generators.py:{name}",
                            "repo_path": None, "synthetic": True})

    for entry in entries:
        path = bench / entry["path"]
        entry["bytes"] = path.stat().st_size
        entry["sha256"] = sha256(path)
    manifest = {"schema": "saqqara-techsheet-inputs/1", "repo_head": head, "inputs": entries}
    (inputs / "MANIFEST.json").write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    for entry in entries:
        print(f"{entry['sha256'][:16]}  {entry['bytes']:>9}  {entry['path']}")


if __name__ == "__main__":
    main()
